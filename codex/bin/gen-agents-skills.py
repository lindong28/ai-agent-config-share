#!/usr/bin/env python3
"""Rebuild ~/.agents/skills — the Agent Skills farm consumed by Codex.

Sources (canonical, never copied):
  claude/skills/*     shared skills            -> per-skill symlink
  codex/skills/*      Codex-only skills        -> per-skill symlink
  claude/commands/**  Claude slash commands    -> generated wrapper SKILL.md
                                                  pointing back at the command file

Idempotent + delete-safe:
- The farm is built complete in a staging dir, then swapped in — an interrupted
  run never leaves a half-built farm.
- Only entries this script owns are dropped on rebuild: symlinks that resolve
  into this repo's skills dirs, and wrapper dirs whose SKILL.md carries the
  GENERATED marker. Anything else (hand-installed skills, foreign symlinks) is
  carried over, and wins name collisions against generated entries.
- If ~/.agents/skills is a symlink NOT owned by install.sh (target outside this
  repo), the script aborts rather than replace the user's setup.
"""

from __future__ import annotations

import fcntl
import json
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FARM = Path.home() / ".agents" / "skills"
SKILL_SOURCES = [REPO / "claude" / "skills", REPO / "codex" / "skills"]
COMMANDS_ROOT = REPO / "claude" / "commands"
MARKER = "<!-- GENERATED by codex/bin/gen-agents-skills.py; source:"

# Fixed exclusions: two Claude-only commands and one legacy alias for a
# canonical skill already present in the farm. Every other command is bridged.
COMMAND_DENYLIST = {
    "custom/supervise-session.md",  # depends on Claude Code transcript/session semantics
    "routine/allow.md",  # manages Claude Code permission-gate learned rules
    "tdd.md",            # legacy shim for tdd-workflow skill
}


def parse_command_meta(md_path: Path) -> tuple[str, bool]:
    """Return (description, explicit_only) from a command file's frontmatter."""
    text = md_path.read_text(encoding="utf-8")
    fm = _frontmatter_lines(text)
    desc = _frontmatter_description(fm) if fm is not None else None
    explicit_only = fm is not None and any(
        re.match(r"^disable-model-invocation:\s*true\b", ln) for ln in fm
    )
    if not desc:
        desc = _first_body_line(text, fm) or f"Claude command {md_path.stem}."
    return desc, explicit_only


def _frontmatter_lines(text: str) -> list[str] | None:
    if not text.startswith("---"):
        return None
    lines = text.splitlines()
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i]
    return None


def _first_body_line(text: str, fm: list[str] | None) -> str | None:
    lines = text.splitlines()
    start = len(fm) + 2 if fm is not None else 0  # skip frontmatter incl. fences
    for line in lines[start:]:
        line = line.strip()
        if line and not line.startswith(("#", "---", "<!--")):
            return line
    return None


def _frontmatter_description(fm: list[str]) -> str | None:
    for i, line in enumerate(fm):
        m = re.match(r"^description:\s*(.*)$", line)
        if not m:
            continue
        value = m.group(1).strip()
        if value in ("|", ">", "|-", ">-", "|+", ">+"):
            block: list[str] = []
            for cont in fm[i + 1:]:
                if cont.strip() == "" or cont.startswith((" ", "\t")):
                    block.append(cont.strip())
                else:
                    break
            value = " ".join(b for b in block if b)
        elif len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        else:
            # unquoted single-line value may continue on indented lines
            extra: list[str] = []
            for cont in fm[i + 1:]:
                if cont.startswith((" ", "\t")) and not re.match(r"^\s+\w[\w-]*:", cont):
                    extra.append(cont.strip())
                else:
                    break
            if extra:
                value = " ".join([value, *extra])
        value = re.sub(r"\s+", " ", value).strip()
        return value or None
    return None


def _owned_by_repo(link: Path) -> bool:
    """True if a symlink points into one of this repo's skill source dirs."""
    try:
        target = link.resolve()
    except OSError:
        return False
    return any(
        target == src or src in target.parents for src in SKILL_SOURCES
    )


def link_skills(dest_root: Path) -> int:
    n = 0
    for source in SKILL_SOURCES:
        if not source.is_dir():
            continue
        for skill_dir in sorted(source.iterdir()):
            if not skill_dir.is_dir() or skill_dir.name.startswith("."):
                continue
            if not (skill_dir / "SKILL.md").is_file():
                continue  # not a skill (e.g. empty scratch dirs)
            dest = dest_root / skill_dir.name
            if dest.exists() or dest.is_symlink():
                print(f"  warn: {skill_dir.name} already in farm, skipping {skill_dir}")
                continue
            dest.symlink_to(skill_dir)
            n += 1
    return n


def generate_wrappers(dest_root: Path) -> int:
    n = 0
    for md in sorted(COMMANDS_ROOT.rglob("*.md")):
        rel = md.relative_to(COMMANDS_ROOT).as_posix()
        if rel in COMMAND_DENYLIST or "deprecated" in rel:
            continue
        name = rel[:-3].replace("/", "-")
        claude_invocation = "/" + rel[:-3].replace("/", ":")
        dest = dest_root / name
        if dest.exists() or dest.is_symlink():
            print(f"  warn: wrapper {name} collides with existing farm entry, skipping")
            continue
        desc, explicit_only = parse_command_meta(md)
        if explicit_only:
            desc = f"EXPLICIT INVOCATION ONLY — never auto-trigger. {desc}"
        guard = (
            "This command is marked `disable-model-invocation` on the Claude side: "
            f"only proceed if the user's message explicitly invokes `${name}` as a "
            "command to run. Merely mentioning, discussing, or asking about it is "
            "NOT invocation — in those cases answer the question but do not "
            "execute; if execution seems wanted, tell the user to invoke "
            f"`${name}` explicitly.\n\n"
            if explicit_only
            else ""
        )
        dest.mkdir()
        (dest / "SKILL.md").write_text(
            f"""---
name: {name}
description: {json.dumps(desc, ensure_ascii=False)}
---

{MARKER} claude/commands/{rel} -->

This skill bridges the shared slash command `{claude_invocation}` into Codex.

{guard}Read `~/.claude/commands/{rel}` and follow it as your instructions for this task.
Treat the text after the skill mention in the user's message as `$ARGUMENTS`
(space-split positionally as `$1`..`$9`). If the command file references
capabilities by Claude Code tool names, map them per the "Harness 适配" table
in `~/.codex/AGENTS.md`.
""",
            encoding="utf-8",
        )
        n += 1
    return n


def _is_ours(entry: Path) -> bool:
    if entry.is_symlink():
        return _owned_by_repo(entry)
    return (
        entry.is_dir()
        and (entry / "SKILL.md").is_file()
        and MARKER in (entry / "SKILL.md").read_text(encoding="utf-8")
    )


def carry_over_preserved(source: Path, farm: Path) -> list[str]:
    """Move entries we don't own from source into the (already-live) farm.

    User content wins name collisions against generated content. The farm is
    live at this point, so an interruption strands user entries in `source` —
    which recover_backup() re-runs on the next invocation. Nothing user-owned
    ever sits in a directory this script deletes wholesale.
    """
    preserved: list[str] = []
    if not source.is_dir():
        return preserved
    for entry in sorted(source.iterdir()):
        if _is_ours(entry):
            continue
        dest = farm / entry.name
        if dest.exists() or dest.is_symlink():
            if dest.is_dir() and not dest.is_symlink():
                shutil.rmtree(dest)
            else:
                dest.unlink()
            print(f"  warn: preserved entry {entry.name} shadows a generated one")
        shutil.move(str(entry), str(dest))
        preserved.append(entry.name)
    return preserved


def recover_backup(backup: Path) -> list[str]:
    """Recover from a previous interrupted run before doing anything else."""
    if not backup.is_dir():
        return []
    if not FARM.exists() and not FARM.is_symlink():
        backup.rename(FARM)  # swap died halfway: restore the old farm wholesale
        return []
    recovered = carry_over_preserved(backup, FARM)
    shutil.rmtree(backup)
    return recovered


def main() -> int:
    FARM.parent.mkdir(parents=True, exist_ok=True)
    # Serialize concurrent rebuilds (git hooks may fire from parallel commits);
    # the lock is held until process exit.
    lock_handle = open(FARM.parent / ".skills.lock", "w")
    fcntl.flock(lock_handle, fcntl.LOCK_EX)

    if FARM.is_symlink():
        if _owned_by_repo(FARM):
            FARM.unlink()  # legacy install.sh link straight into the repo
        else:
            print(
                f"error: {FARM} is a symlink to {FARM.resolve()}, not managed by "
                "this repo — refusing to replace it. Remove it manually to proceed."
            )
            return 1

    staging = FARM.parent / ".skills.staging"
    backup = FARM.parent / ".skills.old"
    recovered = recover_backup(backup)
    if staging.is_dir():
        shutil.rmtree(staging)  # generated content only — safe to discard
    elif staging.is_symlink() or staging.exists():
        staging.unlink()

    # 1. Build the complete generated set in staging (never holds user data).
    staging.mkdir()
    linked = link_skills(staging)
    wrapped = generate_wrappers(staging)

    # 2. Swap: old farm -> backup, staging -> live farm.
    if FARM.exists():
        FARM.rename(backup)
    staging.rename(FARM)

    # 3. Carry user-owned entries from backup into the live farm, then drop it.
    preserved = carry_over_preserved(backup, FARM)
    if backup.is_dir():
        shutil.rmtree(backup)

    print(
        f"agents-skills farm rebuilt: {linked} skills linked, {wrapped} command "
        f"wrappers generated -> {FARM}"
    )
    for name in recovered + preserved:
        print(f"  preserved non-generated entry: {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
