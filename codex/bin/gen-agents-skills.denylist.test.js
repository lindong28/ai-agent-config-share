#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { after, before, test } = require("node:test");

const REPO = path.resolve(__dirname, "../..");
const GENERATOR = path.join(__dirname, "gen-agents-skills.py");
const GENERATED_MARKER = "<!-- GENERATED by codex/bin/gen-agents-skills.py; source:";
const RUN_PROGRAM_COMMAND = "custom/run-program.md";
const RUN_PROGRAM_WRAPPER = "custom-review-agent-harness";
const NORMAL_WRAPPER = "custom-create-handoff";
const APPROVED_DENYLIST = new Set(["routine/allow.md", "tdd.md"]);
const LEGACY_ALIASES = new Map([["tdd.md", "tdd-workflow"]]);
const RETIRED_ORCHESTRATE_PATHS = [
  "claude/commands/orchestrate.md",
  "codex/prompts/ecc-orchestrate.md",
];
const REAL_AGENTS_DIR = path.join(os.homedir(), ".agents");
const SURROGATE_LEAK_PROBE =
  process.env.GEN_AGENTS_SKILLS_TEST_SURROGATE_LEAK_PROBE === "1";

let fakeHome;
let surrogateHome;
let surrogateAgentsDir;
let surrogateBaseline;
let sentinelSkill;
let subprocessCount = 0;

function extractDenylist(source, label) {
  const parser = String.raw`
import ast
import json
import sys

tree = ast.parse(sys.stdin.read())
matches = []
for statement in tree.body:
    if not isinstance(statement, ast.Assign) or len(statement.targets) != 1:
        continue
    target = statement.targets[0]
    if isinstance(target, ast.Name) and target.id == "COMMAND_DENYLIST":
        matches.append(statement.value)
if len(matches) != 1:
    raise ValueError("expected exactly one simple COMMAND_DENYLIST assignment")
value = matches[0]
if not isinstance(value, ast.Set):
    raise ValueError("COMMAND_DENYLIST must be a set literal")
entries = []
for element in value.elts:
    if not isinstance(element, ast.Constant) or not isinstance(element.value, str):
        raise ValueError("COMMAND_DENYLIST entries must be string literals")
    entries.append(element.value)
if not entries:
    raise ValueError("COMMAND_DENYLIST must be non-empty")
if len(entries) != len(set(entries)):
    raise ValueError("COMMAND_DENYLIST must not contain duplicate entries")
print(json.dumps(entries))
`;
  const result = spawnSync("python3", ["-c", parser], { input: source, encoding: "utf8" });
  assert.equal(
    result.status,
    0,
    `${label} must contain a fully parseable literal COMMAND_DENYLIST: ${result.stderr.trim()}`,
  );
  assert.equal(result.stderr, "");
  const entries = JSON.parse(result.stdout);
  return new Set(entries);
}

function currentCommandFiles(root) {
  const files = [];
  const visit = (directory, prefix = "") => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const relative = path.posix.join(prefix, entry.name);
      if (entry.isDirectory()) visit(path.join(directory, entry.name), relative);
      else if ((entry.isFile() || entry.isSymbolicLink()) && entry.name.endsWith(".md")) {
        files.push(relative);
      }
    }
  };
  visit(root);
  return files.sort();
}

function wrappersForCommands(commands, denylist) {
  return new Set(
    commands
      .filter((file) => !denylist.has(file) && !file.includes("deprecated"))
      .map((file) => file.slice(0, -3).replaceAll("/", "-")),
  );
}

function expectedCurrentWrappers() {
  const commands = currentCommandFiles(path.join(REPO, "claude", "commands"));
  assert.ok(commands.length > 0, "current command scan must be non-empty");
  return wrappersForCommands(commands, APPROVED_DENYLIST);
}

function generatedWrappers(farm) {
  const wrappers = new Set();
  for (const name of fs.readdirSync(farm).sort()) {
    const skillFile = path.join(farm, name, "SKILL.md");
    try {
      if (fs.readFileSync(skillFile, "utf8").includes(GENERATED_MARKER)) wrappers.add(name);
    } catch (error) {
      if (!error || !["ENOENT", "ENOTDIR"].includes(error.code)) throw error;
    }
  }
  assert.ok(wrappers.size > 0, "generated wrapper scan must be non-empty");
  return wrappers;
}

function sorted(values) {
  return [...values].sort();
}

function setDifference(left, right) {
  return new Set([...left].filter((value) => !right.has(value)));
}

function pathContains(parent, candidate) {
  const relative = path.relative(parent, candidate);
  return relative === "" ||
    (relative !== ".." && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative));
}

function resolveWithExistingAncestor(target) {
  const suffix = [];
  let cursor = path.resolve(target);
  while (!fs.existsSync(cursor)) {
    const parent = path.dirname(cursor);
    assert.notEqual(parent, cursor, `no existing ancestor for ${target}`);
    suffix.unshift(path.basename(cursor));
    cursor = parent;
  }
  return path.join(fs.realpathSync(cursor), ...suffix);
}

function assertTempRootSeparatedFromRealAgents(tempRoot, realAgentsDir) {
  const resolvedTempRoot = resolveWithExistingAncestor(tempRoot);
  const resolvedRealAgents = resolveWithExistingAncestor(realAgentsDir);
  if (pathContains(resolvedRealAgents, resolvedTempRoot)) {
    assert.fail(
      `FAIL unsafe temp root overlaps real agents directory: temp=${resolvedTempRoot}; ` +
        `real-agents=${resolvedRealAgents}`,
    );
  }
  return resolvedTempRoot;
}

function pinnedMetadata(stat) {
  return {
    mode: stat.mode.toString(),
    uid: stat.uid.toString(),
    gid: stat.gid.toString(),
    ino: stat.ino.toString(),
    nlink: stat.nlink.toString(),
    size: stat.size.toString(),
    mtimeNs: stat.mtimeNs.toString(),
    ctimeNs: stat.ctimeNs.toString(),
    birthtimeNs: stat.birthtimeNs.toString(),
  };
}

function snapshotTree(root) {
  const entries = new Map();
  const visit = (target, relative) => {
    const stat = fs.lstatSync(target, { bigint: true });
    const record = { metadata: pinnedMetadata(stat) };
    if (stat.isFile()) {
      record.kind = "file";
      record.bytes = fs.readFileSync(target).toString("base64");
    } else if (stat.isSymbolicLink()) {
      record.kind = "symlink";
      record.target = fs.readlinkSync(target);
    } else if (stat.isDirectory()) {
      record.kind = "directory";
    } else {
      record.kind = "other";
    }
    entries.set(relative, record);
    if (record.kind === "directory") {
      for (const name of fs.readdirSync(target).sort()) {
        visit(path.join(target, name), path.join(relative, name));
      }
    }
  };
  visit(root, ".");
  return entries;
}

function absoluteSnapshotPath(root, relative) {
  return relative === "." ? root : path.join(root, relative);
}

function assertTreeUnchanged(root, baseline, context) {
  let current;
  try {
    current = snapshotTree(root);
  } catch (error) {
    const target = error && error.path ? error.path : root;
    assert.fail(
      `FAIL damaged the surrogate agents tree: ${target} could not be snapshotted ${context} ` +
        `(${error && error.code ? error.code : "unknown"})`,
    );
  }
  for (const relative of sorted(current.keys())) {
    if (!baseline.has(relative)) {
      assert.fail(
        `FAIL leaked into the surrogate agents tree: ${absoluteSnapshotPath(root, relative)} ` +
          `was added ${context}`,
      );
    }
  }
  for (const relative of sorted(baseline.keys())) {
    const target = absoluteSnapshotPath(root, relative);
    if (!current.has(relative)) {
      assert.fail(`FAIL damaged the surrogate agents tree: ${target} is absent ${context}`);
    }
    if (JSON.stringify(current.get(relative)) !== JSON.stringify(baseline.get(relative))) {
      assert.fail(
        `FAIL damaged the surrogate agents tree: ${target} has different bytes or pinned metadata ` +
          context,
      );
    }
  }
}

function assertNoTestPath(root, context) {
  const target = path.join(root, "skills", sentinelSkill);
  let status = "present";
  try {
    fs.lstatSync(target);
  } catch (error) {
    if (error && error.code === "ENOENT") status = "absent";
    else {
      assert.fail(
        `FAIL could not prove the test-owned path absent from the real farm ${context}: ` +
          `${target} (${error && error.code ? error.code : "unknown"})`,
      );
    }
  }
  assert.equal(
    status,
    "absent",
    `FAIL test-owned path appeared in the real farm ${context}: ${target}`,
  );
}

function assertNoRealTestPath(context) {
  assertNoTestPath(REAL_AGENTS_DIR, context);
}

function resetSurrogate() {
  fs.rmSync(surrogateAgentsDir, { recursive: true, force: true });
  const sentinelDir = path.join(surrogateAgentsDir, "skills", sentinelSkill);
  fs.mkdirSync(sentinelDir, { recursive: true });
  fs.writeFileSync(path.join(sentinelDir, "SKILL.md"), "# Surrogate sentinel\n");
  surrogateBaseline = snapshotTree(surrogateAgentsDir);
}

function runGenerator() {
  subprocessCount++;
  const probe = SURROGATE_LEAK_PROBE;
  const result = spawnSync("python3", [GENERATOR], {
    encoding: "utf8",
    env: { ...process.env, HOME: probe ? surrogateHome : fakeHome },
  });
  try {
    assertTreeUnchanged(
      surrogateAgentsDir,
      surrogateBaseline,
      `after subprocess ${subprocessCount}`,
    );
    assertNoRealTestPath(`after subprocess ${subprocessCount}`);
  } finally {
    if (probe) resetSurrogate();
  }
  return result;
}

before(() => {
  const safeTempRoot = assertTempRootSeparatedFromRealAgents(os.tmpdir(), REAL_AGENTS_DIR);
  sentinelSkill = `gen-agents-skills-test-${process.pid}-${crypto.randomUUID()}`;
  fakeHome = fs.mkdtempSync(path.join(safeTempRoot, "gen-agents-skills-test-home-"));
  surrogateHome = fs.mkdtempSync(path.join(safeTempRoot, "gen-agents-skills-surrogate-home-"));
  surrogateAgentsDir = path.join(surrogateHome, ".agents");
  resetSurrogate();
  assertTreeUnchanged(surrogateAgentsDir, surrogateBaseline, "before the first subprocess");
  assertNoRealTestPath("before the first subprocess");
});

after(() => {
  let failure;
  try {
    assertTreeUnchanged(surrogateAgentsDir, surrogateBaseline, "at suite end");
    assertNoRealTestPath("at suite end");
  } catch (error) {
    failure = error;
  } finally {
    if (fakeHome) fs.rmSync(fakeHome, { recursive: true, force: true });
    if (surrogateHome) fs.rmSync(surrogateHome, { recursive: true, force: true });
  }
  if (failure) throw failure;
  console.log(
    `surrogate-farm whole-tree protection: PASS (${surrogateBaseline.size} paths matched exactly ` +
      `after ${subprocessCount} subprocess)`,
  );
  console.log(
    `real-farm read-only protection: PASS (test-owned path stayed absent after ` +
      `${subprocessCount} subprocess)`,
  );
});

test("denylist exactly matches the fixed approved exclusions", () => {
  const current = extractDenylist(fs.readFileSync(GENERATOR, "utf8"), "current generator");
  assert.deepEqual(
    sorted(current),
    sorted(APPROVED_DENYLIST),
    "COMMAND_DENYLIST may contain only the Claude-only command and verified legacy alias",
  );
});

test("fixed-authority expected wrapper set exactly matches the generated fake-HOME farm", () => {
  const result = runGenerator();
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stderr, "");

  const farm = path.join(fakeHome, ".agents", "skills");
  const expected = expectedCurrentWrappers();
  const actual = generatedWrappers(farm);
  const missing = sorted(setDifference(expected, actual));
  const extra = sorted(setDifference(actual, expected));
  assert.deepEqual(
    { missing, extra },
    { missing: [], extra: [] },
    "generated-marker wrapper set must exactly match current commands minus fixed approved exclusions",
  );
  assert.equal(
    fs.existsSync(path.join(farm, RUN_PROGRAM_WRAPPER)),
    true,
    "custom-review-agent-harness wrapper must exist in the Codex farm",
  );
  const runProgramSkill = fs.readFileSync(path.join(farm, RUN_PROGRAM_WRAPPER, "SKILL.md"), "utf8");
  assert.match(runProgramSkill, /EXPLICIT INVOCATION ONLY/);
  assert.match(runProgramSkill, /only proceed if the user's message explicitly invokes `\$custom-review-agent-harness`/);
  assert.match(runProgramSkill, /Read `~\/\.claude\/commands\/custom\/review-agent-harness\.md`/);
  assert.match(runProgramSkill, /map them per the "Harness 适配" table/);
  const normalSkill = fs.readFileSync(path.join(farm, NORMAL_WRAPPER, "SKILL.md"), "utf8");
  assert.ok(normalSkill.includes(GENERATED_MARKER), "an ordinary command wrapper must still generate");
  console.log(
    `fixed-authority current-command wrapper exact-set comparison: PASS (expected=${expected.size}, ` +
      `actual=${actual.size}, missing=0, extra=0)`,
  );
  console.log("custom-run-program explicit wrapper: PASS; custom-create-handoff wrapper present");
});

test("every excluded legacy alias has a current canonical skill source", () => {
  const skillRoots = [path.join(REPO, "claude", "skills"), path.join(REPO, "codex", "skills")];
  for (const [command, skill] of LEGACY_ALIASES) {
    assert.ok(APPROVED_DENYLIST.has(command), `${command} must remain an approved exclusion`);
    const matches = skillRoots.filter((root) => fs.existsSync(path.join(root, skill, "SKILL.md")));
    assert.ok(matches.length > 0, `${command} canonical skill ${skill} must exist in current sources`);
  }
});

test("retired orchestrate entry has no Claude command or Codex prompt residue", () => {
  for (const relative of RETIRED_ORCHESTRATE_PATHS) {
    assert.equal(fs.existsSync(path.join(REPO, relative)), false, `${relative} must be removed`);
  }
  // 上游用 codex/prompts/ecc-prompts-manifest.txt 再断言一次该 prompt 已退役；
  // 本仓不收录上游 prompts，故只保留上面的文件不存在断言。
});

test("denylist parser fails closed on unsupported Python expressions", () => {
  assert.throws(
    () => extractDenylist(
      'COMMAND_DENYLIST = BASE_DENYLIST | {"custom/run-program.md"}\n',
      "synthetic unsupported generator",
    ),
    /must contain a fully parseable literal COMMAND_DENYLIST:[\s\S]*must be a set literal/,
  );
  console.log("denylist parser unsupported-expression guard: PASS (failed closed)");
});

test("denylist parser accepts Python string literal forms without a trailing comma", () => {
  const parsed = extractDenylist(
    "COMMAND_DENYLIST = {\n    'one.md',\n    \"two.md\"\n}\n",
    "synthetic literal generator",
  );
  assert.deepEqual(sorted(parsed), ["one.md", "two.md"]);
});

test("expected wrapper authority follows unrelated current command additions and deletions", () => {
  assert.deepEqual(
    sorted(wrappersForCommands(["future/new-command.md", RUN_PROGRAM_COMMAND], APPROVED_DENYLIST)),
    ["custom-run-program", "future-new-command"],
  );
  assert.deepEqual(sorted(wrappersForCommands([], APPROVED_DENYLIST)), []);
});

test("current command inventory includes md symlinks without descending symlinked directories", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "gen-agents-skills-command-inventory-"));
  try {
    fs.writeFileSync(path.join(root, "regular.md"), "# regular\n");
    fs.mkdirSync(path.join(root, "real-directory"));
    fs.writeFileSync(path.join(root, "real-directory", "nested.md"), "# nested\n");
    fs.symlinkSync("regular.md", path.join(root, "linked.md"));
    fs.symlinkSync("real-directory", path.join(root, "linked-directory"));
    assert.deepEqual(
      currentCommandFiles(root),
      ["linked.md", "real-directory/nested.md", "regular.md"],
    );
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("surrogate snapshot guard names an unexpected generated path", () => {
  const guardRoot = fs.mkdtempSync(path.join(os.tmpdir(), "gen-agents-skills-guard-"));
  try {
    const baseline = snapshotTree(guardRoot);
    const leaked = path.join(guardRoot, "unexpected-wrapper");
    fs.mkdirSync(leaked);
    assert.throws(
      () => assertTreeUnchanged(guardRoot, baseline, "guard self-test"),
      new RegExp(`FAIL leaked into the surrogate agents tree: ${leaked}`),
    );
  } finally {
    fs.rmSync(guardRoot, { recursive: true, force: true });
  }
});

test("temp-root guard rejects only roots inside the real agents tree", () => {
  const guardRoot = fs.mkdtempSync(path.join(os.tmpdir(), "gen-agents-skills-temp-guard-"));
  const nested = path.join(guardRoot, "nested");
  try {
    fs.mkdirSync(nested);
    assert.throws(
      () => assertTempRootSeparatedFromRealAgents(nested, guardRoot),
      /FAIL unsafe temp root overlaps real agents directory:/,
    );
    assert.doesNotThrow(() => assertTempRootSeparatedFromRealAgents(guardRoot, nested));
  } finally {
    fs.rmSync(guardRoot, { recursive: true, force: true });
  }
});

test("real-farm guard names a test-owned path", () => {
  const guardRoot = fs.mkdtempSync(path.join(os.tmpdir(), "gen-agents-skills-real-guard-"));
  const target = path.join(guardRoot, "skills", sentinelSkill);
  try {
    fs.mkdirSync(target, { recursive: true });
    assert.throws(
      () => assertNoTestPath(guardRoot, "guard self-test"),
      new RegExp(`FAIL test-owned path appeared in the real farm guard self-test: ${target}`),
    );
  } finally {
    fs.rmSync(guardRoot, { recursive: true, force: true });
  }
});
